"""Generate/check the browser's versioned hot-coiled rule snapshot."""
import json
from pathlib import Path
import re
import sys
root=Path(__file__).resolve().parents[1]
rules=json.loads((root/'config/spring_standards/gbt_23934_2015.json').read_text(encoding='utf-8'))
path=root/'frontend/accuracy-inference.js'
text=path.read_text(encoding='utf-8')
line='  const HOT_RULES = '+json.dumps(rules,ensure_ascii=False,separators=(',',':'))+'; // Generated by scripts/sync_hot_coiled_rules.py.'
updated=re.sub(r'^  const HOT_RULES = .*$',lambda _:line,text,flags=re.M)
if '--check' in sys.argv:
    assert text==updated, 'Run scripts/sync_hot_coiled_rules.py to update the browser snapshot'
else:
    path.write_text(updated,encoding='utf-8')
